"""Find normalized population rows resembling Step 6 excluded names."""

import argparse
import html
import json
from collections import defaultdict
from contextlib import redirect_stdout
from io import StringIO
from pathlib import Path

import duckdb

from src.detours.detour_hcr_algebra.shared import markdown_table
from src.helpers.name_matching import docx_name_norm_sql, normalized_tokens_sql
from src.helpers.schema import (
    POPULATION_ECON_TABLE,
    POPULATION_ECON_VIEW,
    POPULATION_NAMES_TABLE,
    POPULATION_TABLE,
)
from src.helpers.vars import (
    KTP_FIRST_NAME_COL,
    KTP_HCR_FILENAME_COL,
    KTP_HCR_ROW_NUMBER_COL,
    KTP_LAST_NAME_COL,
    KTP_POPULATION_INDEX_COL,
)
from src.steps.step_06_build_outerdict_stub import excluded_name_condition_sql

DB_PATH = Path("data/scisci_process.duckdb")
MATCH_LABEL = "excluded_rows_match"
MATCH_EXCLUDED_TOKENS_KEY = "excluded_name_tokens"
MATCH_TARGET_KEY = "candidate_name_norm"
IDENTITY_COLUMNS = (
    KTP_POPULATION_INDEX_COL,
    KTP_HCR_FILENAME_COL,
    KTP_HCR_ROW_NUMBER_COL,
    KTP_FIRST_NAME_COL,
    KTP_LAST_NAME_COL,
)
IDENTITY_COLS = frozenset(IDENTITY_COLUMNS)


def cell(value: object) -> str:
    if value is None:
        return "NULL"
    if value == "":
        return "''"
    text = (
        json.dumps(value, ensure_ascii=False, default=str)
        if isinstance(value, (list, dict))
        else str(value)
    )
    return html.escape(text, quote=False).replace("|", "\\|").replace("\n", "<br>")


def main() -> None:
    con = duckdb.connect(str(DB_PATH), read_only=True)
    try:
        con.execute("SET threads = 1")
        con.execute("SET memory_limit = '128MB'")
        con.execute("CREATE TEMP MACRO unaccent(value) AS strip_accents(value)")
        first = f'p."{KTP_FIRST_NAME_COL}"'
        last = f'p."{KTP_LAST_NAME_COL}"'
        name = f"COALESCE({first}, '') || ' ' || COALESCE({last}, '')"
        normalized_tokens_expression = normalized_tokens_sql(name)
        tokens_sql_template = "list_sort(list_distinct({normalized_tokens_sql}))"
        tokens_sql = tokens_sql_template.format(normalized_tokens_sql=normalized_tokens_expression)
        excluded_condition_sql = excluded_name_condition_sql(first, last)
        exclusion_sql_template = (
            f'SELECT p."{KTP_POPULATION_INDEX_COL}", p."{KTP_HCR_FILENAME_COL}",\n'
            f'       p."{KTP_HCR_ROW_NUMBER_COL}", {first}, {last},\n'
            '       {tokens_sql} AS excluded_name_tokens\n'
            f'FROM {POPULATION_ECON_VIEW} p\n'
            'WHERE {excluded_name_condition_sql}'
        )
        exclusion_sql = exclusion_sql_template.format(
            tokens_sql=tokens_sql,
            excluded_name_condition_sql=excluded_condition_sql,
        )
        excluded_rows = sorted(con.execute(exclusion_sql).fetchall(), key=lambda row: row[0])
        groups = defaultdict(list)
        for row in excluded_rows:
            tokens = tuple(row[5])
            if not tokens:
                raise ValueError(f"Excluded row {row[0]} has no searchable name tokens")
            groups[tokens].append(row)

        candidate_norm_sql = docx_name_norm_sql(name)
        match_sql_template = (
            "WITH excluded_award_rows AS (\n"
            "    {exclusion_sql}\n"
            "),\n"
            "token_groups AS (\n"
            "    SELECT DISTINCT excluded_name_tokens\n"
            "    FROM excluded_award_rows\n"
            ")\n"
            "SELECT g.excluded_name_tokens, p.*, n.candidate_name_norm\n"
            "FROM token_groups g\n"
            f"CROSS JOIN {POPULATION_ECON_VIEW} p\n"
            "CROSS JOIN LATERAL (\n"
            "    SELECT {docx_name_norm_sql} AS candidate_name_norm\n"
            ") n\n"
            "WHERE list_bool_and(\n"
            "    list_transform(\n"
            "        g.excluded_name_tokens,\n"
            "        token -> strpos(n.candidate_name_norm, token) > 0\n"
            "    )\n"
            ")\n"
            f'ORDER BY p."{KTP_POPULATION_INDEX_COL}"'
        )
        match_sql = match_sql_template.format(
            exclusion_sql=exclusion_sql.replace("\n", "\n    "),
            docx_name_norm_sql=candidate_norm_sql,
        )
        cursor = con.execute(match_sql)
        columns = [column[0] for column in cursor.description][1:-1]
        position = {column: i for i, column in enumerate(columns)}
        hits = defaultdict(list)
        candidate_names = {}
        for matched in cursor.fetchall():
            tokens = tuple(matched[0])
            row = matched[1:-1]
            hits[tokens].append(row)
            candidate_names[row[position[KTP_POPULATION_INDEX_COL]]] = matched[-1]
    finally:
        con.close()

    print("# HCR award rows matching excluded names\n")
    print(f"Generated by `{Path(__file__).name}`.\n")
    print(
        f"`{POPULATION_ECON_VIEW}` is the Step 4 view joining "
        f"`{POPULATION_TABLE}` (Clarivate XLSX award rows loaded in Step 2), "
        f"`{POPULATION_NAMES_TABLE}` (normalized column names derived in Step 3), and "
        f"`{POPULATION_ECON_TABLE}` (Step 4 economy and priority fields). "
        "This detour reads it read-only.\n"
    )
    print(
        "The first query uses Step 6's exact null/empty-name predicate on all award "
        "rows; Step 6's persisted exclusion archive covers sampled rows only. The "
        "second query matches each distinct excluded-name token group to award rows "
        "whose compact names contain every token, regardless of order. "
        "`unaccent` is a session-local alias for `strip_accents`. The templates "
        "below expand the named SQL snippets before execution.\n"
    )
    print("### Excluded award rows\n\n```sql")
    print(f"-- normalized_tokens_sql(name)\n{normalized_tokens_expression}\n")
    print(f"-- tokens_sql\n{tokens_sql_template}\n")
    print(f"-- excluded_name_condition_sql(first, last)\n{excluded_condition_sql}\n")
    print(f"-- exclusion_sql template\n{exclusion_sql_template}\n```\n")
    print("### Matching award rows\n\n```sql")
    print(f"-- docx_name_norm_sql(name)\n{candidate_norm_sql}\n")
    print(f"-- match_sql template\n{match_sql_template}\n```\n")
    summary_headers = ("Population index", "XLSX file", "XLSX row", "First name", "Last name")
    for tokens, sources in groups.items():
        matches = hits[tokens]
        name = " ".join(part for part in sources[0][3:5] if part)
        print(f"## {cell(name)}\n")
        print(f"Excluded award rows: **{len(sources)}**.\n")
        markdown_table(
            summary_headers,
            [tuple(cell(value) for value in source[:5]) for source in sources],
        )
        print(f"Matching award rows: **{len(matches)}**.\n")
        markdown_table(
            summary_headers,
            [
                tuple(cell(row[position[column]]) for column in IDENTITY_COLUMNS)
                for row in matches
            ],
        )
        for row in matches:
            index = row[position[KTP_POPULATION_INDEX_COL]]
            print(
                f"### Award row {index}: {cell(row[position[KTP_HCR_FILENAME_COL]])} "
                f"#{row[position[KTP_HCR_ROW_NUMBER_COL]]}\n"
            )
            payload = json.dumps(
                {
                    MATCH_EXCLUDED_TOKENS_KEY: tokens,
                    MATCH_TARGET_KEY: candidate_names[index],
                },
                ensure_ascii=False,
                separators=(",", ":"),
            )
            print(f"`{MATCH_LABEL}`: `{payload}`\n")
            fields = [
                (column, cell(value))
                for column, value in zip(columns, row, strict=True)
                if column in IDENTITY_COLS or value not in (None, "")
            ]
            markdown_table(("Field", "Value"), fields)


def cli() -> None:
    parser = argparse.ArgumentParser(description="Search HCR rows for Step 6 excluded names.")
    parser.add_argument("-o", "--output", type=Path, help="Write Markdown to PATH; default stdout")
    args = parser.parse_args()
    if args.output is None:
        main()
    else:
        report = StringIO()
        with redirect_stdout(report):
            main()
        args.output.write_text(report.getvalue().rstrip("\n") + "\n", encoding="utf-8")


if __name__ == "__main__":
    cli()
